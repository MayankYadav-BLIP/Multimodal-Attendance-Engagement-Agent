const sessionId = document.body.dataset.sessionId;
const btn = document.getElementById("suggest-btn");
const source = document.getElementById("suggest-source");
const list = document.getElementById("suggest-list");

document.querySelectorAll(".bar[data-h]").forEach(el => {
    el.style.height = el.dataset.h + "px";
});

btn.addEventListener("click", async () => {
    btn.disabled = true;
    source.textContent = "Generating suggestions...";
    list.innerHTML = "";
    try {
        const res = await fetch("/api/suggestions/" + sessionId);
        const data = await res.json();
        if (!res.ok) {
            source.textContent = data.error || "Could not get suggestions.";
        } else {
            data.items.forEach(text => {
                const li = document.createElement("li");
                li.textContent = text;
                list.appendChild(li);
            });
            source.textContent = data.source === "gemini"
                ? "Generated by Gemini (" + data.model + ") from a numbers-only summary."
                : "Generated by built-in rules (no internet used). " + (data.note || "");
        }
    } catch (e) {
        source.textContent = "Could not reach the server.";
    }
    btn.disabled = false;
});